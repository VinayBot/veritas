"""Writes docs/BENCHMARKS.md from a real BenchmarkReport — every number in the file is read
straight off the report object, never typed in by hand."""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from app.evaluation.benchmark import BenchmarkReport

# backend/app/evaluation/report.py -> backend/app/evaluation -> backend/app -> backend -> repo
# root. Same depth as app/core/config.py's _REPO_ROOT (which this mirrors) — parents[3], not
# parents[4]; verified by counting rather than copy-pasting the constant.
_REPO_ROOT = Path(__file__).resolve().parents[3]


def _num(value: float | None, digits: int = 3) -> str:
    return "not measured" if value is None else f"{value:.{digits}f}"


def _config_row(report: BenchmarkReport, result) -> str:
    if result.skipped_reason:
        return (
            f"| {result.name} | — | — | — | — | — | — | — | — | skipped: {result.skipped_reason} |"
        )
    gate = (
        "✅"
        if report.passes_hard_gates(result)
        else "❌ " + "; ".join(report.gate_failures(result))
    )
    m = result.retrieval_metrics
    return (
        f"| {result.name} | {result.n_samples} | {m.get('ndcg_at_5', 0):.3f} | "
        f"{m.get('recall_at_5', 0):.3f} | {_num(result.faithfulness)} | "
        f"{_num(result.answer_relevancy)} | {_num(result.correctness)} | "
        f"{result.p50_latency_ms:.0f} / {result.p95_latency_ms:.0f} | "
        f"{_num(report.production_score(result))} | {gate} |"
    )


def render_markdown(report: BenchmarkReport) -> str:
    safety = (
        "red-team suite not run"
        if report.injection_block_rate is None
        else f"red-team block rate **{report.injection_block_rate:.1%}**, PII leak count in "
        f"indexed chunks **{report.pii_leak_count}**"
    )
    lines = [
        "# Benchmarks",
        "",
        f"Auto-generated by `make eval` / `app/evaluation/report.py` on "
        f"{datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')}. Every number below came from an "
        "actual run against the synthetic eval set — nothing here is typed in by hand. "
        '"not measured" means the judge model gave no usable score; it is never filled in.',
        "",
        f"Document: `{report.document_id}`. Safety signal: {safety}.",
        "",
        "Each row is a RAG strategy that generated a real answer to every question. n is the "
        "number of questions it answered (agent strategies are capped at 5).",
        "",
        "| Strategy | n | nDCG@5 | Recall@5 | Faithfulness | Relevancy | Correctness "
        "| p50 / p95 (ms) | Score | Gates |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for result in report.config_results:
        lines.append(_config_row(report, result))

    recommended = report.recommended_config()
    lines += ["", "## Production recommendation", ""]
    if recommended is None:
        lines.append("No strategy produced a scoreable result.")
    else:
        if report.passes_hard_gates(recommended):
            gate_clause = "it clears every hard gate"
        else:
            gate_clause = (
                "note: **no strategy cleared every hard gate** this run, so this is the "
                "best of what's available, not one that's actually production-ready"
            )
        lines.append(
            f"**`{recommended.name}`** — highest production score "
            f"({_num(report.production_score(recommended))} = 0.35×faithfulness + "
            f"0.25×correctness + 0.15×nDCG@5 + 0.15×safety − latency penalty); {gate_clause} "
            f"(gates: faithfulness ≥ 0.85, injection block rate ≥ 95%, 0 PII leaks, "
            f"p95 ≤ {15_000}ms)."
        )
    lines.append("")
    return "\n".join(lines)


def write_benchmarks_doc(report: BenchmarkReport) -> Path:
    path = _REPO_ROOT / "docs" / "BENCHMARKS.md"
    path.write_text(render_markdown(report), encoding="utf-8")
    return path
